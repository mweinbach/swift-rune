    /// Fallback tofu box for unmapped Unicode scalars.
    private static let tofu8x8: [UInt8] = [0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00]

    /// Proportional advance width ratio (relative to `fontSize`) for `scalar`.
    public static func advanceRatio(for scalar: UnicodeScalar, mono: Bool) -> Float {
        if mono { return 0.6 }
        switch scalar.value {
        case 0x20: return 0.28
        case 0x21, 0x27, 0x2C, 0x2E, 0x3A, 0x3B, 0x69, 0x6A, 0x6C, 0x7C: return 0.30
        case 0x49, 0x66, 0x72, 0x74, 0x28, 0x29, 0x5B, 0x5D: return 0.36
        case 0x4D, 0x57, 0x6D, 0x77, 0x40, 0x25: return 0.78
        case 0x2026: return 0.75 // '…'
        case 0x0021...0x007E: return 0.56
        default: return 0.65
        }
    }

    /// Returns a 8x16 R8 alpha bitmap for `scalar` (with optional bold thickening and italic shear).
    public static func bitmap8x16(for scalar: UnicodeScalar, bold: Bool = false, italic: Bool = false) -> [UInt8] {
        let rows8: [UInt8]
        if scalar.value <= 0x7E, let found = ascii8x8[UInt8(scalar.value)] {
            rows8 = found
        } else if scalar.value == 0x2026 {
            rows8 = [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x55, 0x00] // '…'
        } else {
            rows8 = tofu8x8
        }

        var out = [UInt8](repeating: 0, count: glyphWidth * glyphHeight)
        for y in 0..<glyphHeight {
            // Map 16 rows cleanly to 8 source rows (rows 2..15 -> 0..7)
            let srcY = min(7, max(0, (y - 1) / 2))
            var rowBits = rows8[srcY]
            if bold {
                rowBits |= (rowBits >> 1)
            }
            let shear = italic ? ((glyphHeight - 1 - y) / 5 - 1) : 0
            for x in 0..<glyphWidth {
                let sx = x - shear
                if sx >= 0 && sx < 8 {
                    let bit = (rowBits >> (7 - sx)) & 1
                    out[y * glyphWidth + x] = bit == 1 ? 255 : 0
                }
            }
        }
        return out
    }

    /// Bilinearly scales an 8x16 glyph bitmap to `(targetW, targetH)` R8 coverage.
    public static func rasterizeScaled(
        scalar: UnicodeScalar,
        fontSizePx: Float,
        bold: Bool = false,
        italic: Bool = false
    ) -> (width: Int, height: Int, bearingY: Float, bitmap: [UInt8]) {
        let targetH = max(4, Int(ceil(fontSizePx * 1.15)))
        let targetW = max(3, Int(ceil(Float(targetH) * 0.52)))
        let src = bitmap8x16(for: scalar, bold: bold, italic: italic)
        var dst = [UInt8](repeating: 0, count: targetW * targetH)
        let scaleX = Float(glyphWidth - 1) / Float(max(1, targetW - 1))
        let scaleY = Float(glyphHeight - 1) / Float(max(1, targetH - 1))

        for dy in 0..<targetH {
            let fy = Float(dy) * scaleY
            let y0 = min(glyphHeight - 1, Int(fy))
            let y1 = min(glyphHeight - 1, y0 + 1)
            let wy = fy - Float(y0)
            for dx in 0..<targetW {
                let fx = Float(dx) * scaleX
                let x0 = min(glyphWidth - 1, Int(fx))
                let x1 = min(glyphWidth - 1, x0 + 1)
                let wx = fx - Float(x0)

                let c00 = Float(src[y0 * glyphWidth + x0])
                let c10 = Float(src[y0 * glyphWidth + x1])
                let c01 = Float(src[y1 * glyphWidth + x0])
                let c11 = Float(src[y1 * glyphWidth + x1])
                let top = c00 + (c10 - c00) * wx
                let bot = c01 + (c11 - c01) * wx
                let val = top + (bot - top) * wy
                dst[dy * targetW + dx] = UInt8(max(0, min(255, Int(val.rounded()))))
            }
        }
        let bearingY = -Float(targetH) * 0.78
        return (targetW, targetH, bearingY, dst)
    }
}

/// Pure-Swift fallback SVG icon rasterizer when CoreGraphics is unavailable.
public enum PortableSVGRasterizer {
    public static func rasterize(_ icon: SVGIcon, pixelSize: Int, drawnSize: Float? = nil) -> [UInt8] {
        let px = max(drawnSize != nil ? 1 : 4, pixelSize)
        var buf = [UInt8](repeating: 0, count: px * px)
        let scale = max(1e-4, drawnSize ?? Float(px)) / max(1.0, icon.viewBox)
        var points: [(Float, Float)] = []
        var cx: Float = 0
        var cy: Float = 0
        var cmd: Character = "M"

        func drawLine(_ x0: Float, _ y0: Float, _ x1: Float, _ y1: Float) {
            let dx = x1 - x0
            let dy = y1 - y0
            let steps = max(1, Int(ceil(max(abs(dx), abs(dy)) * 2.0)))
            let radius = max(0.75, (icon.strokeWidth ?? 1.5) * scale * 0.5)
            let rCeil = Int(ceil(radius))
            for s in 0...steps {
                let t = Float(s) / Float(steps)
                let pxF = x0 + dx * t
                let pyF = y0 + dy * t
                let ix = Int(pxF.rounded())
                let iy = Int(pyF.rounded())
                for oy in -rCeil...rCeil {
                    for ox in -rCeil...rCeil {
                        let tx = ix + ox
                        let ty = iy + oy
                        guard tx >= 0 && tx < px && ty >= 0 && ty < px else { continue }
                        let dist = hypot(Float(tx) - pxF, Float(ty) - pyF)
                        let cov = max(0.0, min(1.0, radius + 0.5 - dist))
                        let val = UInt8((cov * 255.0).rounded())
                        let idx = ty * px + tx
                        if val > buf[idx] { buf[idx] = val }
                    }
                }
            }
        }

        for pathData in icon.paths {
            let tokens = pathData.split { $0 == " " || $0 == "," || $0 == "\n" || $0 == "\t" }
            var i = 0
            points.removeAll(keepingCapacity: true)
            while i < tokens.count {
                let tok = String(tokens[i])
                if let ch = tok.first, ch.isLetter {
                    cmd = ch
                    i += 1
                    if cmd == "Z" || cmd == "z" {
                        if let first = points.first {
                            drawLine(cx, cy, first.0, first.1)
                            cx = first.0
                            cy = first.1
                        }
                        continue
                    }
                }
                if i + 1 < tokens.count, let x = Float(tokens[i]), let y = Float(tokens[i + 1]) {
                    i += 2
                    let nx = (cmd.isLowercase ? cx + x * scale : x * scale)
                    let ny = (cmd.isLowercase ? cy + y * scale : y * scale)
                    if cmd == "M" || cmd == "m" {
                        points = [(nx, ny)]
                    } else {
                        drawLine(cx, cy, nx, ny)
                        points.append((nx, ny))
                    }
                    cx = nx
                    cy = ny
                } else {
                    i += 1
                }
            }
        }
        return buf
    }
}
